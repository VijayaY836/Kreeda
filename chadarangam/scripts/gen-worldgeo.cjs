// One-off generator: converts world-atlas's countries-110m TopoJSON into
// plain SVG path strings using a simple equirectangular projection, plus
// precomputed pixel positions for our historical waypoints (projected with
// the exact same formula, so pins and coastlines are guaranteed aligned).
//
// Run with: node scripts/gen-worldgeo.cjs
const fs = require('fs');
const path = require('path');
const topojson = require('topojson-client');
const world = require('world-atlas/countries-110m.json');

const MAPW = 1600, MAPH = 800;
function proj(lon, lat) {
  const x = (lon + 180) / 360 * MAPW;
  const y = (90 - lat) / 180 * MAPH;
  return [x, y];
}
function fmt(n) { return Math.round(n * 10) / 10; }

// Some rings (Russia, Fiji, ...) cross the antimeridian as raw -180/+180
// longitude jumps. Under a plain linear projection that reads as a single
// point leaping clear across the map, so split the ring into separate
// subpaths wherever consecutive points jump by more than half the map width.
function ringToPath(ring) {
  let d = '';
  let broken = true;
  let prevX = null;
  for (const [lon, lat] of ring) {
    const [x, y] = proj(lon, lat);
    if (prevX !== null && Math.abs(x - prevX) > MAPW / 2) broken = true;
    d += `${broken ? 'M' : 'L'}${fmt(x)},${fmt(y)}`;
    broken = false;
    prevX = x;
  }
  return d + 'Z';
}

function geometryToPath(geom) {
  if (geom.type === 'Polygon') {
    return geom.coordinates.map(ringToPath).join(' ');
  }
  if (geom.type === 'MultiPolygon') {
    return geom.coordinates.map((poly) => poly.map(ringToPath).join(' ')).join(' ');
  }
  return '';
}

const geo = topojson.feature(world, world.objects.countries);
const EXCLUDE = new Set(['Antarctica']);

const countries = geo.features
  .filter((f) => f.properties && !EXCLUDE.has(f.properties.name))
  .map((f) => ({ name: f.properties.name, d: geometryToPath(f.geometry) }))
  .filter((c) => c.d.length > 0);

// --- Kashmir / Gilgit-Baltistan / Aksai Chin patch -------------------------
// The 110m dataset draws this region along the de-facto Line of Control /
// Line of Actual Control, which excludes Pakistan- and China-administered
// portions of the former princely state from India's polygon. This app
// depicts the full Jammu & Kashmir & Ladakh region as a single undivided
// landmass (matching how it's shown on Indian maps), by layering an
// approximate patch of that combined outline over the existing polygons in
// India's fill colour, so the seam disappears into the shared land colour.
const KASHMIR_RING = [
  [74.5, 32.6], [73.9, 33.6], [73.6, 34.3], [73.0, 34.6], [73.9, 35.5],
  [74.3, 36.0], [75.0, 36.6], [75.9, 36.9], [76.8, 36.1], [78.0, 35.6],
  [79.5, 34.7], [79.3, 33.5], [78.7, 32.9], [77.8, 32.4], [76.5, 32.3],
  [75.3, 32.1], [74.5, 32.6],
];
const kashmirPatchD = ringToPath(KASHMIR_RING);

// --- historical waypoints, projected with the identical formula ------------
const WAYPOINTS = [
  { key: 'pataliputra', lon: 85.14, lat: 25.61 },
  { key: 'hyderabad', lon: 78.49, lat: 17.39 },
  { key: 'ctesiphon', lon: 44.58, lat: 33.09 },
  { key: 'baghdad', lon: 44.36, lat: 33.31 },
  { key: 'cordoba', lon: -4.78, lat: 37.88 },
  { key: 'valencia', lon: -0.38, lat: 39.47 },
  { key: 'xian', lon: 108.95, lat: 34.27 },
  { key: 'kyoto', lon: 135.77, lat: 35.01 },
].map((p) => {
  const [x, y] = proj(p.lon, p.lat);
  return { ...p, x: fmt(x), y: fmt(y) };
});

const out = `// AUTO-GENERATED by scripts/gen-worldgeo.cjs — do not hand-edit.
// Source: world-atlas countries-110m (Natural Earth via TopoJSON), projected
// with a plain equirectangular formula: x=(lon+180)/360*W, y=(90-lat)/180*H.
export const MAPW = ${MAPW};
export const MAPH = ${MAPH};

export interface CountryPath { name: string; d: string; }
export const COUNTRIES: CountryPath[] = ${JSON.stringify(countries)};

// India + the full Jammu & Kashmir / Ladakh region as one undivided outline —
// layered over the base country polygons in India's fill colour.
export const KASHMIR_PATCH_D = ${JSON.stringify(kashmirPatchD)};

export interface Waypoint { key: string; lon: number; lat: number; x: number; y: number; }
export const WAYPOINTS: Waypoint[] = ${JSON.stringify(WAYPOINTS)};
`;

const outPath = path.join(__dirname, '..', 'src', 'assets', 'worldGeo.ts');
fs.writeFileSync(outPath, out);
console.log('wrote', outPath, '-', (out.length / 1024).toFixed(1), 'KB,', countries.length, 'countries');
